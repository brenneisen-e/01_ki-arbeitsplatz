    function formatCompact(val) {
        var abs = Math.abs(val);
        if (abs >= 1000000000) return (val / 1000000000).toFixed(1) + 'B';
        if (abs >= 1000000) return (val / 1000000).toFixed(1) + 'M';
        if (abs >= 1000) return (val / 1000).toFixed(0) + 'K';
        return String(val);
    }

