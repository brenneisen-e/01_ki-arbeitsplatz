// Helpers
export function formatCompact(val) {
  const abs = Math.abs(val);
  if (abs >= 1000000000) return (val / 1000000000).toFixed(1) + 'B';
  if (abs >= 1000000) return (val / 1000000).toFixed(1) + 'M';
  if (abs >= 1000) return (val / 1000).toFixed(0) + 'K';
  return String(val);
}

export function formatAmount(amount, ccy) {
  const prefix = amount < 0 ? '-' : '+';
  const abs = Math.abs(amount);
  let formatted;
  if (abs >= 1000000) formatted = (abs / 1000000).toFixed(1) + 'M';
  else if (abs >= 1000) formatted = (abs / 1000).toFixed(0) + 'K';
  else formatted = String(abs);
  return { text: `${prefix}${ccy} ${formatted}`, positive: amount >= 0 };
}

export function getStepType(wf) {
  if (wf.event.toLowerCase().includes('cash')) return 'cashflow';
  if (wf.event.toLowerCase().includes('sod')) return 'sod';
  return 'rebalance';
}

export function getCurrentTimestamp() {
  const now = new Date();
  const dd = String(now.getDate()).padStart(2, '0');
  const mm = String(now.getMonth() + 1).padStart(2, '0');
  const yyyy = now.getFullYear();
  const hh = String(now.getHours()).padStart(2, '0');
  const min = String(now.getMinutes()).padStart(2, '0');
  return `${dd}.${mm}.${yyyy}, ${hh}:${min}`;
}
