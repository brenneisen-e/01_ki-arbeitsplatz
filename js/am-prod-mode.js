    window.ampContextAction = function(action, wfId) {
        removeContextMenu();
        var wf = WORKFLOWS.filter(function(w) { return w.id === wfId; })[0];
        if (!wf) return;

        if (action === 'advance') {
            ampShowActionModal(wfId);
        } else if (action === 'view') {
            // Switch to Portfolios tab and highlight the portfolio
            activeTab = 'portfolios';
            workflowExpandedId = null;
            renderProdMode();
        } else if (action === 'pause') {
            wf.status = 'paused';
            wf.action = 'Paused';
            workflowExpandedId = null;
            renderProdMode();
        } else if (action === 'reset') {
            wf.step = 0;
            wf.status = 'attention';
            var stepType = getStepType(wf);
            var steps = WORKFLOW_STEPS[stepType];
            wf.action = steps[0] ? steps[0].label : 'Draft';
            workflowExpandedId = null;
            renderProdMode();
        }
    };

    window.ampAdvanceWorkflow = function(wfId) {
        var wf = WORKFLOWS.filter(function(w) { return w.id === wfId; })[0];
        if (!wf) return;

        wf.step = Math.min(wf.step + 1, wf.totalSteps);
        if (wf.step >= wf.totalSteps) {
            wf.status = 'completed';
            wf.action = 'Trading';
        } else {
            var stepType = getStepType(wf);
            var steps = WORKFLOW_STEPS[stepType];
            if (steps[wf.step]) {
                wf.action = steps[wf.step].label;
            }
        }
        workflowExpandedId = null;
        renderProdMode();
    };

